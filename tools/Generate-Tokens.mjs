// Generates the web CSS block, the Android theme values and the iOS theme values
// from design/tokens/tuvima.tokens.json (Look v3.2 D11).
// Run `node tools/Generate-Tokens.mjs` to write; add `--check` to only compare (exit 1 on drift).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const sourcePath = join(root, 'design/tokens/tuvima.tokens.json');
export const cssPath = join(root, 'src/MediaEngine.Web/wwwroot/tuvima.tokens.css');
export const androidPath = join(root, 'clients/android/mobile/src/main/java/com/tuvima/library/mobile/TuvimaTokens.kt');
export const iosPath = join(root, 'clients/apple/iOS/TuvimaTokens.swift');
const begin = '    /* BEGIN GENERATED TOKENS (design/tokens/tuvima.tokens.json; edit there, then run node tools/Generate-Tokens.mjs) */';
const end = '    /* END GENERATED TOKENS */';

export function loadTokens() {
  return JSON.parse(readFileSync(sourcePath, 'utf8')).tokens;
}

const cssValue = t => (t.unit === 'px' ? `${t.value}px` : String(t.value));

export function cssBlock(tokens) {
  const lines = [begin];
  for (const t of tokens) {
    if (t.group) lines.push(`    /* ${t.group} */`);
    lines.push(`    ${t.css}: ${cssValue(t)};`);
  }
  lines.push(end);
  return lines.join('\n');
}

/** Removes a hand-written duplicate of a generated token from the :root body (4-space indent, same value only). */
function stripDuplicates(css, tokens) {
  let out = css;
  for (const t of tokens) {
    const re = new RegExp(`^    ${t.css.replace(/[-]/g, '\\-')}:\\s*${cssValue(t).replace(/[#.]/g, '\\$&')};[^\\n]*\\r?\\n`, 'mi');
    out = out.replace(re, '');
  }
  return out;
}

export function applyCss(css, tokens) {
  const eol = css.includes('\r\n') ? '\r\n' : '\n';
  const norm = css.replace(/\r\n/g, '\n');
  const block = cssBlock(tokens);
  const re = new RegExp(`${begin.replace(/[()*./]/g, '\\$&')}[\\s\\S]*?${end.replace(/[*./]/g, '\\$&')}`);
  let next;
  if (re.test(norm)) {
    next = norm.replace(re, block);
  } else {
    const marker = ':root {\n    color-scheme: dark;\n';
    if (!norm.includes(marker)) throw new Error('tuvima.tokens.css :root marker not found');
    next = stripDuplicates(norm, tokens).replace(marker, `${marker}\n${block}\n`);
  }
  return next.replace(/\n/g, eol);
}

const argb = hex => `0xFF${hex.slice(1).toUpperCase()}`;

export function androidSource(tokens) {
  const L = [
    '// <auto-generated> from design/tokens/tuvima.tokens.json by tools/Generate-Tokens.mjs. Do not edit by hand. </auto-generated>',
    'package com.tuvima.library.mobile',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    '',
    'object TuvimaTokens {',
  ];
  for (const t of tokens) {
    if (t.unit === 'color') L.push(`    val ${t.name} = Color(${argb(t.value)})`);
    else if (t.unit === 'px') L.push(`    val ${t.name} = ${t.value}.dp`);
    else L.push(`    const val ${t.name} = ${t.value}`);
  }
  L.push('}', '');
  return L.join('\n');
}

export function iosSource(tokens) {
  const L = [
    '// Generated from design/tokens/tuvima.tokens.json by tools/Generate-Tokens.mjs. Do not edit by hand.',
    'import SwiftUI',
    '',
    'enum TuvimaTokens {',
  ];
  for (const t of tokens) {
    if (t.unit === 'color') {
      const h = t.value.slice(1);
      const c = i => (parseInt(h.slice(i, i + 2), 16) / 255).toFixed(4);
      L.push(`    static let ${t.name} = Color(red: ${c(0)}, green: ${c(2)}, blue: ${c(4)})`);
    } else {
      L.push(`    static let ${t.name}: CGFloat = ${t.value}`);
    }
  }
  L.push('}', '');
  return L.join('\n');
}

export function expected() {
  const tokens = loadTokens();
  return [
    [cssPath, applyCss(readFileSync(cssPath, 'utf8'), tokens)],
    [androidPath, androidSource(tokens)],
    [iosPath, iosSource(tokens)],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let drift = false;
  for (const [path, text] of expected()) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === text) continue;
    if (check) { console.error(`Out of date: ${path}. Run: node tools/Generate-Tokens.mjs`); drift = true; }
    else writeFileSync(path, text);
  }
  process.exit(drift ? 1 : 0);
}
